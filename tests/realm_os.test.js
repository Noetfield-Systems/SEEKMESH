import test from 'node:test';
import assert from 'node:assert/strict';
import {DatabaseSync} from 'node:sqlite';
import {RealmOS} from '../realm-os/engine.js';

function fixture(){
 const db=new DatabaseSync(':memory:');
 db.exec("CREATE TABLE resources(id INTEGER PRIMARY KEY AUTOINCREMENT,name TEXT,url TEXT,category TEXT);");
 db.exec("CREATE TABLE submissions(id INTEGER PRIMARY KEY AUTOINCREMENT,state TEXT,category TEXT,reviewed_at TEXT,created_at TEXT);");
 db.exec("CREATE TABLE autonomy_jobs(id INTEGER PRIMARY KEY,status TEXT,last_error TEXT);");
 db.exec("CREATE TABLE autonomy_audits(id INTEGER PRIMARY KEY,status TEXT);");
 db.exec("CREATE TABLE autonomy_candidates(id INTEGER PRIMARY KEY,state TEXT,url TEXT,name TEXT,description TEXT,category TEXT,score INTEGER,last_seen_at TEXT,http_status INTEGER);");
 db.exec("CREATE TABLE realm_guilds(id INTEGER PRIMARY KEY);");
 db.exec("CREATE TABLE realm_guild_members(id INTEGER PRIMARY KEY);");
 db.exec("CREATE TABLE realm_guild_posts(id INTEGER PRIMARY KEY,status TEXT);");
 db.exec("CREATE TABLE realm_guild_reports(id INTEGER PRIMARY KEY);");
 db.exec("CREATE TABLE mesh_members(id INTEGER PRIMARY KEY,is_synthetic INTEGER NOT NULL DEFAULT 0);");
 db.exec("CREATE TABLE mesh_wallet_links(member_id INTEGER);");
 db.exec("CREATE TABLE mesh_sponsors(id INTEGER PRIMARY KEY);");
 db.exec("CREATE TABLE realm_event_counts(day TEXT,event TEXT,target TEXT,count INTEGER);");
 db.prepare('INSERT INTO resources(name,url,category) VALUES(?,?,?)').run('A','https://example.org','Builders');
 const aut={status:()=>({connectedWorkers24h:0,activeExecutors:0,logicalWorkerShards:2048,schedulerRunning:true,paused:false,budget:{requestsUsed:0,requestsMax:160},lastTick:null,consecutiveErrors:0})};
 const os=new RealmOS(db,{autonomy:aut,community:{launchReport:()=>({})}});
 return {db,os};
}
test('RealmOS: persistent ten-agent runtime, no fictitious paid workers, idempotent weekly expeditions',()=>{
 const {db,os}=fixture();
 const status=os.status();
 assert.equal(status.logicalAgentRoles,10);
 assert.equal(status.physicalOSAgents,0);
 assert.equal(status.liveWeb3SettlementsVerified,0);
 assert.equal(status.tokenIssued,false);
 assert.equal(status.phases[0].status,'operating');
 assert.equal(status.phases.find(x=>x.id==='commerce').progress,0);
 const first=os.pulse({force:true});
 assert.equal(first.ok,true);
 assert.equal(first.expeditionsCreated,1);
 assert.ok(os.status().expeditions.length===1);
 assert.equal(os.expedition()[0].accepted,0);
 const second=os.pulse({force:true});
 assert.equal(second.expeditionsCreated,0);
 assert.equal(db.prepare('SELECT COUNT(*) n FROM realm_os_expeditions').get().n,1);
 assert.equal(db.prepare("SELECT COUNT(*) n FROM realm_os_receipts WHERE kind='os.pulse'").get().n,2);
 const restarted=new RealmOS(db,{autonomy:os.autonomy});
 assert.equal(restarted.expedition()[0].unique_key,os.expedition()[0].unique_key);
 db.close();
});
test('RealmOS: real goal measurement, expedition proof, no emitted extra rewards',()=>{
 const {db,os}=fixture();
 os.pulse({force:true});
 const cat=os.expedition()[0].category;
 db.prepare("INSERT INTO submissions(state,category,reviewed_at,created_at) VALUES('approved',?,datetime('now'),datetime('now'))").run(cat);
 assert.equal(os.expedition()[0].accepted,1);
 assert.equal(os.goals().find(x=>x.metric==='accepted_sources').actual,1);
 assert.equal(db.prepare('SELECT COUNT(*) n FROM realm_os_packets WHERE kind=?').get('build_stablecoin_mission').n,1);
 assert.equal(os.public().physicalOSAgents,0);
 db.close();
});
test('RealmOS: founder controls require evidence; never mark payout independently verified',()=>{
 const {db,os}=fixture();
 os.pulse({force:true});
 const r=os.admin();
 assert.equal(r.agents.length,10);
 assert.ok(r.packets.find(x=>x.kind==='build_stablecoin_mission'));
 const packet=r.packets.find(x=>x.kind==='enable_paid_agent_queries');
 assert.ok(packet);
 assert.ok(os.control({action:'evidence',packetId:packet.id,evidence:'short'}).error);
 const done=os.control({action:'evidence',packetId:packet.id,evidence:'The founder reviewed the x402 integration plan; no settlement was made.'});
 assert.equal(done.ok,true);
 assert.equal(done.independentVerification,false);
 assert.equal(os.admin().packets.find(x=>x.id===packet.id).status,'observed');
 assert.equal(os.control({action:'goal',goalId:'commerce:verified_x402_payments',target:2}).ok,true);
 assert.equal(os.goals().find(x=>x.metric==='verified_x402_payments').target,2);
 assert.ok(os.control({action:'goal',goalId:'commerce:verified_x402_payments',target:-1}).error);
 assert.equal(os.control({action:'pause'}).paused,true);
 assert.equal(os.pulse({force:true}).reason,'paused_or_disabled');
 assert.equal(os.control({action:'resume'}).paused,false);
 db.close();
});
